export const recipeDatabase: BabyRecipe[] = rawRecipeDatabase.map(item => {
  const names = recipeNamesById[item.id];

  return {
    ...item,
    title: `${names.vi} / ${names.en}`,
    vietnameseTitle: names.vi,
    englishTitle: names.en,
  };
});

export function getRecipesForMonth(month: number): BabyRecipe[] {
  return recipeDatabase.filter(item => item.month === Math.max(6, Math.min(12, month)));
}
